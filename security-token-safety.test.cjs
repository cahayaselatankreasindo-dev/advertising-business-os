'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('index.html', 'utf8');
const sync = fs.readFileSync('sync-safe.js', 'utf8');
const backend = fs.readFileSync('google_apps_script.js', 'utf8');
const labCode = fs.readFileSync('apps-script/Code.gs', 'utf8');
const guard = fs.readFileSync('apps-script/LabRequestGuard.gs', 'utf8');
const readme = fs.readFileSync('README.md', 'utf8');
assert.match(html, /let sessionApiToken = ''/);
assert.match(html, /function getApiToken\(\) \{ return sessionApiToken; \}/);
assert.match(html, /function scrubPersistedApiTokens\(\)/);
assert.match(html, /delete db\.settings\.apiToken/);
assert.doesNotMatch(html, /db\.settings\.apiToken\s*=/);
assert.doesNotMatch(html, /tokenEl\.value\s*=\s*db\.settings\.apiToken/);
assert.doesNotMatch(sync, /\?token=/);
assert.match(sync, /action: 'read', token: token \|\| '', protocolVersion: PROTOCOL_VERSION/);
assert.match(sync, /mode: 'cors'/);
assert.match(sync, /redirect: 'follow'/);
assert.match(backend, /function doGet\(\)[\s\S]*?POST_REQUIRED/);
assert.match(backend, /case "read"/);
assert.match(labCode, /function doGet\(\)[\s\S]*?POST_REQUIRED/);
assert.match(labCode, /case "read"/);
assert.match(guard, /action === "read"/);
assert.match(readme, /memori tab selama sesi aktif/);
console.log('Security token transport contract passed');
